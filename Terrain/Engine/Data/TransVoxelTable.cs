    public static void LoadTransVoxelBuffers(ComputeShader shader, int kernelId)
    {
        shader.SetBuffer(kernelId, "TransitionCellClass", TransitionCellClassBuffer());
        shader.SetBuffer(kernelId, "TransitionGeometryCounts", TransitionGeometryCountsBuffer());
        shader.SetBuffer(kernelId, "TransitionTriTable", TransitionTriTableBuffer());
        shader.SetBuffer(kernelId, "TransitionCornerOffsets", TransitionCornerOffsetsBuffer());
        shader.SetBuffer(kernelId, "TransitionVertexData", TransitionVertexDataBuffer());
    }

    public static ComputeBuffer TransitionCellClassBuffer()
    {
        // store as uint stride=4 for simplicity
        uint[] u = new uint[transitionCellClass.Length];
        for (int i = 0; i < u.Length; i++) u[i] = transitionCellClass[i];
        var buf = new ComputeBuffer(u.Length, sizeof(uint), ComputeBufferType.Structured);
        buf.SetData(u);
        return buf;
    }

    public static ComputeBuffer TransitionGeometryCountsBuffer()
    {
        int count = TransitionGeometryCounts.Length;
        var buffer = new ComputeBuffer(count, sizeof(uint), ComputeBufferType.Structured);
        buffer.SetData(TransitionGeometryCounts);
        return buffer;
    }

    public static ComputeBuffer TransitionTriTableBuffer()
    {
        // Flatten 56x36 -> 2016 ints
        int[] flat = FlattenInt(TransitionTriTable);
        var buffer = new ComputeBuffer(flat.Length, sizeof(int), ComputeBufferType.Structured);
        buffer.SetData(flat);
        return buffer;
    }

    public static ComputeBuffer TransitionCornerOffsetsBuffer()
    {
        int count = TransitionCornerOffsets.Length;
        var buffer = new ComputeBuffer(count, sizeof(uint), ComputeBufferType.Structured);
        buffer.SetData(TransitionCornerOffsets);
        return buffer;
    }

    public static ComputeBuffer TransitionVertexDataBuffer()
    {
        // Flatten 512x12 -> 6144 uints
        uint[] flat = FlattenUInt(TransitionVertexData);
        var buffer = new ComputeBuffer(flat.Length, sizeof(uint), ComputeBufferType.Structured);
        buffer.SetData(flat);
        return buffer;
    }

    private static int[] FlattenInt(int[,] src)
    {
        int rows = src.GetLength(0);
        int cols = src.GetLength(1);
        int[] dst = new int[rows * cols];
        Buffer.BlockCopy(src, 0, dst, 0, rows * cols * sizeof(int));
        return dst;
    }

    private static uint[] FlattenUInt(uint[,] src)
    {
        int rows = src.GetLength(0);
        int cols = src.GetLength(1);
        uint[] dst = new uint[rows * cols];
        // BlockCopy uses bytes; safe for primitive arrays, including multi-dim.
        Buffer.BlockCopy(src, 0, dst, 0, rows * cols * sizeof(uint));
        return dst;
    }

